type Key = keyof (typeof dictionaries)["en"];

interface I18n {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: Key, vars?: Record<string, string | number>) => string;
  /** Translate a server enum value with a prefix (e.g. "sev", "Critical"); falls back to the raw value. */
  term: (prefix: string, value: string | null | undefined) => string;
  formatDate: (iso: string | null | undefined) => string;
  formatNumber: (n: number) => string;
}

const I18nContext = createContext<I18n | null>(null);
const STORAGE_KEY = "atlas.lang";

function initialLang(): Lang {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored === "en" || stored === "pt-BR") return stored;
  } catch {
    /* storage unavailable */
  }
  return navigator.language.toLowerCase().startsWith("pt") ? "pt-BR" : "en";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);

  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    try {
      localStorage.setItem(STORAGE_KEY, next);
    } catch {
      /* ignore */
    }
  }, []);

  const value = useMemo<I18n>(() => {
    const dict = dictionaries[lang] as Record<string, string>;
    const t: I18n["t"] = (key, vars) => {
      let text = dict[key] ?? dictionaries.en[key] ?? key;
      if (vars) for (const [k, v] of Object.entries(vars)) text = text.replace(`{${k}}`, String(v));
      return text;
    };
    const term: I18n["term"] = (prefix, v) => (v ? (dict[`${prefix}.${v}`] ?? v) : "—");
    const dateFmt = new Intl.DateTimeFormat(lang, { dateStyle: "medium", timeStyle: "short" });
    const numFmt = new Intl.NumberFormat(lang);
    return {
      lang,
      setLang,
      t,
      term,
      formatDate: (iso) => (iso ? dateFmt.format(new Date(iso)) : "—"),
      formatNumber: (n) => numFmt.format(n),
    };
  }, [lang, setLang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18n {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider");
  return ctx;
}
